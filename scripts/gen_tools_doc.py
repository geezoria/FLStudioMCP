"""Regenerate docs/TOOLS.md from the live tool registry.

    python scripts/gen_tools_doc.py           # write docs/TOOLS.md
    python scripts/gen_tools_doc.py --check   # exit 1 if docs/TOOLS.md is stale (CI)
"""

from __future__ import annotations

import asyncio
import logging
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "TOOLS.md"


def _signature(schema: dict) -> str:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    parts = [name if name in required else f"{name}?" for name in props]
    return ", ".join(parts)


def _summary(description: str | None) -> str:
    text = (description or "").strip().split("\n\n")[0]
    return " ".join(text.split()).replace("|", "\\|")


def _kind(annotations) -> str:
    if annotations is None:
        return ""
    if annotations.read_only_hint:
        return "read"
    return "write ⚠" if annotations.destructive_hint else "write"


async def _render() -> str:
    os.environ.pop("FLMCP_TOOLSETS", None)
    os.environ.pop("FLMCP_DISABLE_TOOLS", None)
    logging.disable(logging.CRITICAL)
    from fl_studio_mcp import server
    from fl_studio_mcp.tools._toolsets import GROUPS

    app = server.build_app()
    tools = {t.name: t for t in await app.list_tools()}
    listing = (await app.call_tool("fl_list_toolsets", {})).structured_content
    groups = listing["groups"]
    resources = await app.list_resources()
    prompts = await app.list_prompts()

    out = [
        "# fLMCP — Tool reference",
        "",
        "<!-- Generated by scripts/gen_tools_doc.py — do not edit by hand. -->",
        "",
        f"{len(tools)} tools, {len(resources)} resources, {len(prompts)} prompts. "
        "Parameters marked `?` are optional. **Kind**: `read` tools never change the "
        "project (clients may auto-approve them); `write ⚠` tools are flagged "
        "destructive in their MCP annotations.",
        "",
        "Index conventions: channel indices are global and 0-based, pattern numbers are "
        "1-based, mixer track 0 is Master.",
        "",
        "Groups can be selected with `FLMCP_TOOLSETS` (see the README).",
        "",
    ]
    for name, description, _ in GROUPS:
        names = groups[name]["enabled_tools"]
        out += [f"## `{name}` — {description} ({len(names)})", "",
                "| Tool | Parameters | Kind | Description |", "| --- | --- | --- | --- |"]
        for tool_name in names:
            t = tools[tool_name]
            out.append(f"| `{t.name}` | {_signature(t.input_schema)} | {_kind(t.annotations)} "
                       f"| {_summary(t.description)} |")
        out.append("")

    out += ["## Resources", "", "| URI | Description |", "| --- | --- |"]
    for r in resources:
        out.append(f"| `{r.uri}` | {_summary(r.description)} |")
    out += ["", "## Prompts", "", "| Prompt | Arguments | Description |", "| --- | --- | --- |"]
    for p in prompts:
        args = ", ".join(a.name if a.required else f"{a.name}?" for a in (p.arguments or []))
        out.append(f"| `{p.name}` ({p.title or ''}) | {args} | {_summary(p.description)} |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    sys.path.insert(0, str(ROOT / "src"))
    text = asyncio.run(_render())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/TOOLS.md is stale - run: python scripts/gen_tools_doc.py")
            return 1
        print("docs/TOOLS.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
